// Language configuration
const supportedLanguages = ['fr', 'de', 'it'];
const defaultLanguage = 'fr';

/**
 * Detect browser language and return matching supported language
 */
function detectBrowserLanguage() {
    // Check localStorage first (user preference)
    const savedLang = localStorage.getItem('vergasta-lang');
    if (savedLang && supportedLanguages.includes(savedLang)) {
        return savedLang;
    }

    // Get browser language
    const browserLang = navigator.language || navigator.userLanguage;
    const langCode = browserLang.split('-')[0].toLowerCase();

    // Return matching language or default
    if (supportedLanguages.includes(langCode)) {
        return langCode;
    }

    return defaultLanguage;
}

/**
 * Get current language
 */
function getCurrentLanguage() {
    return localStorage.getItem('vergasta-lang') || detectBrowserLanguage();
}

/**
 * Set language and save preference
 */
function setLanguage(lang) {
    if (!supportedLanguages.includes(lang)) {
        console.warn(`Language "${lang}" not supported. Using default.`);
        lang = defaultLanguage;
    }

    localStorage.setItem('vergasta-lang', lang);
    applyTranslations(lang);
    updateLanguageSelector(lang);
    updateHtmlLang(lang);
}

/**
 * Update the html lang attribute
 */
function updateHtmlLang(lang) {
    document.documentElement.lang = lang;
}

/**
 * Apply translations to all elements with data-i18n attribute
 */
function applyTranslations(lang) {
    const t = translations[lang];
    if (!t) return;

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (t[key]) {
            element.textContent = t[key];
        }
    });

    // Update elements with data-i18n-html (for HTML content)
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
        const key = element.getAttribute('data-i18n-html');
        if (t[key]) {
            element.innerHTML = t[key];
        }
    });

    // Update page title
    const pageType = document.body.getAttribute('data-page');
    if (pageType === 'index' && t.siteTitle) {
        document.title = t.siteTitle;
    } else if (pageType === 'privacy' && t.privacyTitle) {
        document.title = t.privacyTitle;
    } else if (pageType === 'terms' && t.termsTitle) {
        document.title = t.termsTitle;
    } else if (pageType === 'imprint' && t.imprintTitle) {
        document.title = t.imprintTitle;
    }
}

/**
 * Update language selector UI
 */
function updateLanguageSelector(lang) {
    // Update active state on language buttons
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang-btn');
        if (btnLang === lang) {
            btn.classList.add('bg-accent-lime', 'text-ink');
            btn.classList.remove('text-swiss-grey', 'hover:text-ink');
        } else {
            btn.classList.remove('bg-accent-lime', 'text-ink');
            btn.classList.add('text-swiss-grey', 'hover:text-ink');
        }
    });
}

/**
 * Create language selector HTML
 */
function createLanguageSelector() {
    return `
        <div class="flex items-center gap-1 border border-ink bg-white">
            <button data-lang-btn="fr" onclick="setLanguage('fr')" class="px-2 py-1 text-xs font-mono font-bold transition-colors">FR</button>
            <button data-lang-btn="de" onclick="setLanguage('de')" class="px-2 py-1 text-xs font-mono font-bold transition-colors">DE</button>
            <button data-lang-btn="it" onclick="setLanguage('it')" class="px-2 py-1 text-xs font-mono font-bold transition-colors">IT</button>
        </div>
    `;
}

/**
 * Initialize i18n on page load
 */
function initI18n() {
    const lang = getCurrentLanguage();
    applyTranslations(lang);
    updateLanguageSelector(lang);
    updateHtmlLang(lang);
}

// Auto-initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
} else {
    initI18n();
}
